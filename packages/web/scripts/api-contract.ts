/**
 * Generates `src/generated/api-operations.ts` from viafrei-api's contract: every GET operation of
 * `api/openapi.json` at a release tag, with its path and query parameters. The site's client (`src/api/client.ts`)
 * is typed to it and refuses a path or a parameter the contract does not have.
 *
 *   gh release download v<X.Y.Z> -R mavrovde/viafrei-api -p openapi.json -p SHA256SUMS -D <dir>
 *   (cd <dir> && shasum -a 256 -c --ignore-missing SHA256SUMS)
 *   npx tsx packages/web/scripts/api-contract.ts <dir>/openapi.json <X.Y.Z>
 *
 * The release's `openapi.json` asset is `api/openapi.json` at the release tag. Never edit the output by hand;
 * regenerate it when the `api` pin of images.pin moves (`test/api-contract.test.ts` holds the two versions equal).
 * exit: 0 written · 2 could not read or parse the contract · 64 usage
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../src/generated/api-operations.ts", import.meta.url));

type Param = { readonly name?: unknown; readonly in?: unknown };
type Operation = { readonly operationId?: unknown; readonly parameters?: readonly Param[] };
type PathItem = { readonly get?: Operation; readonly post?: unknown; readonly put?: unknown; readonly patch?: unknown; readonly delete?: unknown; readonly parameters?: readonly Param[] };
export type OpenApi = { readonly paths?: Readonly<Record<string, PathItem>> };
export type GetOperation = { readonly operationId: string; readonly path: readonly string[]; readonly query: readonly string[] };

/** The `/v1/` GET operations of an OpenAPI document, by path, in path order. */
export function getOperations(doc: OpenApi): Record<string, GetOperation> {
  const out: Record<string, GetOperation> = {};
  const paths = doc.paths ?? {};
  for (const path of Object.keys(paths).sort((a, b) => a.localeCompare(b, "en"))) {
    const item = paths[path];
    const op = item?.get;
    if (op === undefined || !path.startsWith("/v1/")) continue;
    if (typeof op.operationId !== "string") throw new TypeError(`api-contract: GET ${path} has no operationId`);
    const params = [...(item?.parameters ?? []), ...(op.parameters ?? [])];
    const names = (where: string): string[] => params.filter((p) => p.in === where && typeof p.name === "string").map((p) => p.name as string);
    out[path] = { operationId: op.operationId, path: names("path"), query: names("query") };
  }
  return out;
}

/** The generated module for release `version`, whose openapi.json hashes to `sha256`. */
export function render(ops: Readonly<Record<string, GetOperation>>, version: string, sha256: string): string {
  const rows = Object.entries(ops).map(([p, o]) => `  ${JSON.stringify(p)}: { operationId: ${JSON.stringify(o.operationId)}, path: ${JSON.stringify(o.path)}, query: ${JSON.stringify(o.query)} },`);
  return [
    `// GENERATED by packages/web/scripts/api-contract.ts from viafrei-api v${version} api/openapi.json (sha256 ${sha256}). Do not edit.`,
    "",
    "/** The viafrei-api release this site's client is generated from, and the sha256 of its openapi.json. */",
    `export const API_CONTRACT = { version: ${JSON.stringify(version)}, contractSha256: ${JSON.stringify(sha256)} } as const;`,
    "",
    "/** Every GET operation of the contract: its operationId, its path parameters and its query parameters. */",
    "export const API_GET_OPERATIONS = {",
    ...rows,
    "} as const;",
    "",
    "export type ApiGetPath = keyof typeof API_GET_OPERATIONS;",
    "",
  ].join("\n");
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [file, version] = process.argv.slice(2);
  if (file === undefined || version === undefined || !/^\d+\.\d+\.\d+$/.test(version)) {
    console.error("usage: tsx packages/web/scripts/api-contract.ts <openapi.json> <X.Y.Z>");
    process.exit(64);
  }
  let bytes: Buffer;
  let doc: OpenApi;
  try {
    bytes = readFileSync(file);
    doc = JSON.parse(bytes.toString("utf8")) as OpenApi;
  } catch (e) {
    console.error(`✗ api-contract: cannot read ${file}: ${(e as Error).message}`);
    process.exit(2);
  }
  const ops = getOperations(doc);
  writeFileSync(OUT, render(ops, version, createHash("sha256").update(bytes).digest("hex")));
  console.log(`✓ api-contract: ${String(Object.keys(ops).length)} GET operations of viafrei-api v${version} written`);
}
